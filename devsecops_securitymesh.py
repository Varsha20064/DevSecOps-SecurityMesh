"""### 2. Encryption in Transit: Securing Data in Motion

**Encryption in Transit** (also known as encryption in motion) protects data as it moves from one point to another, typically over a network. This prevents eavesdropping and tampering by unauthorized parties during transmission.

The most common example of encryption in transit is **HTTPS** (Hypertext Transfer Protocol Secure), which uses **SSL/TLS** (Secure Sockets Layer/Transport Layer Security) to encrypt communication between a web browser and a server.

SSL/TLS works by establishing a secure channel between two communicating parties, ensuring:
*   **Confidentiality**: Data is encrypted, so only the intended recipient can read it.
*   **Integrity**: Data cannot be modified without detection.
*   **Authentication**: Parties can verify each other's identity.

Let's simulate a very basic secure communication using Python's `http.server` with SSL/TLS.

#### Generating Self-Signed SSL/TLS Certificates

For this demonstration, we'll need SSL/TLS certificates. In a real-world scenario, you would obtain these from a Certificate Authority (CA) like Let's Encrypt. For local testing, we can generate a self-signed certificate.

We'll use `openssl` to create a private key and a self-signed certificate. **Note:** Self-signed certificates are *not* trusted by browsers or other clients by default and will cause security warnings. They are suitable for local development and demonstration only.
"""

import subprocess
import os

# Define certificate and key file names
cert_file = "server.crt"
key_file = "server.key"

# Check if files already exist to avoid regenerating
if not os.path.exists(cert_file) or not os.path.exists(key_file):
    print("Generating self-signed SSL/TLS certificate and private key...")
    try:
        # Generate a private key (2048-bit RSA)
        subprocess.run(
            ['openssl', 'genrsa', '-out', key_file, '2048'],
            check=True, capture_output=True, text=True
        )
        # Generate a self-signed certificate
        # -x509: output a self-signed certificate
        # -nodes: no DES encryption of the private key
        # -days 365: certificate valid for 365 days
        # -new: generate a new certificate request
        # -key: use this key
        # -out: output certificate file
        # -subj: subject information (common name CN is important for hostname matching)
        subprocess.run(
            ['openssl', 'req', '-new', '-x509', '-nodes', '-days', '365',
             '-key', key_file, '-out', cert_file, '-subj', '/CN=localhost'],
            check=True, capture_output=True, text=True
        )
        print(f"Successfully generated '{key_file}' and '{cert_file}'.")
    except subprocess.CalledProcessError as e:
        print(f"Error generating certificates: {e.stderr}")
    except Exception as e:
        print(f"An unexpected error occurred: {e}")
else:
    print(f"SSL/TLS certificate '{cert_file}' and key '{key_file}' already exist.")

# Verify files are present
print(f"Checking for '{key_file}': {os.path.exists(key_file)}")
print(f"Checking for '{cert_file}': {os.path.exists(cert_file)}")

"""#### Implementing a Simple HTTPS Server and Client

Now, let's create a minimal HTTPS server and a client to demonstrate secure communication. Since we are in a Colab environment and need to demonstrate both server and client, we'll run the server in a separate thread and have the client connect to it.
"""

import http.server
import ssl
import threading
import time
import urllib.request

# Configuration
HTTPS_PORT = 8443 # Standard HTTPS port
CERT_FILE = "server.crt"
KEY_FILE = "server.key"

# --- HTTPS Server Class ---
class SecureHandler(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        self.send_response(200)
        self.send_header('Content-type', 'text/html')
        self.end_headers()
        response_message = f"Hello from the secure server! You accessed {self.path} over HTTPS."
        self.wfile.write(response_message.encode('utf-8'))

    def log_message(self, format, *args):
        # Suppress logging to avoid cluttering output when running in thread
        pass

def run_https_server():
    try:
        httpd = http.server.HTTPServer(('localhost', HTTPS_PORT), SecureHandler)

        # Create an SSL context
        ssl_context = ssl.create_default_context(ssl.Purpose.CLIENT_AUTH)
        ssl_context.load_cert_chain(certfile=CERT_FILE, keyfile=KEY_FILE)

        # Wrap the socket with the SSL context
        httpd.socket = ssl_context.wrap_socket(
            httpd.socket,
            server_side=True
        )
        print(f"Secure HTTPS server started on https://localhost:{HTTPS_PORT}/")
        httpd.serve_forever()
    except FileNotFoundError:
        print("Error: Certificate or key file not found. Please run the previous cell to generate them.")
    except Exception as e:
        print(f"Error running HTTPS server: {e}")
    finally:
        print("HTTPS server stopped.")

# --- Client Request Function ---
def make_secure_request():
    url = f"https://localhost:{HTTPS_PORT}/secure-resource"
    print(f"\nAttempting to make a secure request to {url}...")
    try:
        # For self-signed certificates, we must disable SSL verification in the client.
        # In a real application with trusted CAs, you would NOT do this.
        context = ssl._create_unverified_context()
        with urllib.request.urlopen(url, context=context) as response:
            print("Secure Client Response:")
            print(response.read().decode('utf-8'))
    except urllib.error.URLError as e:
        print(f"Client request failed: {e.reason}")
    except ConnectionRefusedError:
        print("Client request failed: Connection refused. Is the server running?")
    except Exception as e:
        print(f"An unexpected error occurred during client request: {e}")

# --- Main Execution ---
print("--- Demonstrating Encryption in Transit (HTTPS) ---")

# Run server in a separate thread
server_thread = threading.Thread(target=run_https_server)
server_thread.daemon = True # Allow main program to exit even if server thread is running
server_thread.start()

# Give the server a moment to start up
time.sleep(2)

# Make the client request
make_secure_request()

