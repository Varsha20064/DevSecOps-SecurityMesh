"""### 2. Advanced Authentication: Password Hashing with `bcrypt`

Storing passwords in plain text, even in the simplified `authenticate_user` function, is a severe security risk. If a database is compromised, all user passwords would be exposed.

**Password Hashing** converts a password into a fixed-size string of characters using a one-way cryptographic function. A good hashing algorithm also incorporates a 'salt' (a random string) to prevent rainbow table attacks, and is computationally intensive to slow down brute-force attacks.

We will use the `bcrypt` library, a robust password-hashing function designed to be resilient against modern attacks.
"""

# Commented out IPython magic to ensure Python compatibility.
# Install bcrypt library
# %pip install bcrypt

import bcrypt

def hash_password(password):
    # Generate a salt and hash the password
    # bcrypt.gensalt() generates a random salt. The work factor (e.g., 12) determines how CPU-intensive the hashing is.
    # Higher work factors are more secure but slower.
    hashed_bytes = bcrypt.hashpw(password.encode('utf-8'), bcrypt.gensalt(rounds=12))
    return hashed_bytes.decode('utf-8') # Store as a UTF-8 string

def verify_password(plain_password, hashed_password):
    # Verify a plain password against a stored hash
    # bcrypt.checkpw automatically extracts the salt from the hashed_password
    return bcrypt.checkpw(plain_password.encode('utf-8'), hashed_password.encode('utf-8'))

